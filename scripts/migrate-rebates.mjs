// Migrates the company's own rebate listings from the legacy site into a typed
// dataset at lib/rebates.ts. It is a faithful copy of chargehomesolutions.com's
// /rebates pages (our own content); every program keeps its official source URL.
//
// Run from the repo root:  node scripts/migrate-rebates.mjs
// Bump REBATES_VERIFIED below whenever you refresh (aim for quarterly).

import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const REBATES_VERIFIED = "August 2026"
const BASE = "https://chargehomesolutions.com"
const UA = { headers: { "User-Agent": "Mozilla/5.0" } }
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "lib", "rebates.ts")

const decode = (s) =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&#x27;|&#39;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&nbsp;/g, " ")
    .replace(/&mdash;/g, "—")
    .replace(/&ndash;/g, "–")
    .replace(/&gt;/g, ">")
    .replace(/&lt;/g, "<")
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim()

async function get(url) {
  const r = await fetch(url, { ...UA, signal: AbortSignal.timeout(20_000) })
  if (!r.ok) throw new Error(`${url} -> HTTP ${r.status}`)
  return r.text()
}

const stateName = (slug) =>
  slug
    .split("-")
    .map((w, i) => (i > 0 && w === "of" ? "of" : w[0].toUpperCase() + w.slice(1)))
    .join(" ")

const CARD =
  /<div class="rounded-xl border border-white\/10 bg-\[#0a1120\] p-5">([\s\S]*?)(?=<div class="rounded-xl border border-white\/10 bg-\[#0a1120\] p-5">|<\/main>|<footer)/g

const CATEGORIES = new Set(["Federal", "State", "Utility"])

function parseState(html, slug) {
  const programs = []
  for (const m of html.matchAll(CARD)) {
    const c = m[1]
    const badge = c.match(/<span class="rounded bg-white\/10[^"]*"[^>]*>([\s\S]*?)<\/span>/)
    const nameM = c.match(/<h3[^>]*>([\s\S]*?)<\/h3>/)
    const amountM = c.match(/<span class="shrink-0 rounded-lg bg-brand\/15[^"]*"[^>]*>([\s\S]*?)<\/span>/)
    const ps = [...c.matchAll(/<p class="mt-1\.5 text-sm leading-relaxed[^"]*">([\s\S]*?)<\/p>/g)].map((p) =>
      decode(p[1]),
    )
    const url = c.match(/<a href="(https?:\/\/[^"]+)"/)
    if (!nameM) continue

    const name = decode(nameM[1])
    const category = badge ? decode(badge[1]) : ""
    const amount = amountM ? decode(amountM[1]) : ""
    const officialUrl = url ? url[1] : ""

    // Fail loudly if the source markup drifts: a silent bad record would emit an
    // invalid category (breaking card styling) or an empty href (a dead link).
    if (!CATEGORIES.has(category)) throw new Error(`${slug}: unknown category "${category}" for "${name}"`)
    if (!amount) throw new Error(`${slug}: missing amount for "${name}"`)
    if (!officialUrl) throw new Error(`${slug}: missing officialUrl for "${name}"`)

    programs.push({ category, name, amount, eligibility: ps[0] || "", detail: ps[1] || null, officialUrl })
  }
  return programs
}

const index = await get(`${BASE}/rebates/`)
const slugs = [...new Set([...index.matchAll(/href="\/rebates\/([a-z-]+)\/"/g)].map((m) => m[1]))].filter(
  (s) => s.length > 1,
)

const data = []
const failures = []
for (const slug of slugs) {
  try {
    const programs = parseState(await get(`${BASE}/rebates/${slug}/`), slug)
    if (programs.length === 0) continue // skip category index pages
    data.push({ slug, state: stateName(slug), programs })
    process.stdout.write(`${slug}:${programs.length} `)
  } catch (e) {
    failures.push(`${slug}: ${e.message}`)
    console.log(`\nFAIL ${slug}: ${e.message}`)
  }
}
console.log("\n")

// Never overwrite the catalog from a partial run: a transient fetch failure
// would silently drop states. Abort with a non-zero exit instead.
if (failures.length > 0) {
  console.error(`Aborting without writing lib/rebates.ts — ${failures.length} state(s) failed:`)
  for (const f of failures) console.error(`  - ${f}`)
  process.exit(1)
}

data.sort((a, b) => a.state.localeCompare(b.state))
const totalPrograms = data.reduce((n, s) => n + s.programs.length, 0)

const file = `// AUTO-GENERATED by scripts/migrate-rebates.mjs — do not hand-edit.
// Faithful migration of chargehomesolutions.com/rebates (our own content);
// every program keeps its official source URL so users can verify. Refresh quarterly.

export type RebateCategory = "Federal" | "State" | "Utility"

export type RebateProgram = {
  category: RebateCategory
  name: string
  /** Headline dollar figure, verbatim from the source (e.g. "Up to $2,500"). */
  amount: string
  /** Who qualifies / where it applies. */
  eligibility: string
  /** Extra detail, when the source provided a second line. */
  detail: string | null
  /** Official program page for the user to verify eligibility. */
  officialUrl: string
}

export type StateRebates = {
  slug: string
  state: string
  programs: RebateProgram[]
}

/** When this snapshot was captured from the source pages. */
export const REBATES_VERIFIED = ${JSON.stringify(REBATES_VERIFIED)}

export const rebateTotals = {
  states: ${data.length},
  programs: ${totalPrograms},
} as const

export const rebates: StateRebates[] = ${JSON.stringify(data, null, 2)}

const bySlug = new Map(rebates.map((s) => [s.slug, s]))

export function getStateRebates(slug: string): StateRebates | undefined {
  return bySlug.get(slug)
}

/** Lightweight list for the index page and selectors. */
export function rebateStateList(): { slug: string; state: string; count: number }[] {
  return rebates.map((s) => ({ slug: s.slug, state: s.state, count: s.programs.length }))
}
`

fs.writeFileSync(OUT, file)
console.log(`wrote ${OUT}\nstates: ${data.length}  programs: ${totalPrograms}`)
